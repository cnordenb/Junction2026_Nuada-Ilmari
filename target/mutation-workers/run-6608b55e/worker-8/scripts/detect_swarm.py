# Verdict rules. "strong" and "moderate" clusters count as flagged.
STRONG_SCORE, STRONG_BEATS, STRONG_SIZE = 70.0, 99.5, 8
MODERATE_SCORE, MODERATE_BEATS = 45.0, 99.0
DEFAULT_MIN_SIZE = 5         # a "swarm" of fewer posts is too easy to produce by accident
MAX_CHART_TIMES = 1500       # post times per group sent along for charts

CAVEATS = [
    "Scores describe patterns in text and timing, not who is behind them. A flagged cluster is a "
    "reason for a person to look closer, not proof of bots or coordination.",
    "Innocent causes of similar, synchronised posts include breaking news, quotes, memes, "
    "greetings, giveaways and messages generated by the platform itself.",
]
NO_ACCOUNTS_CAVEAT = ("No account column was used, so one person reposting their own text cannot be "
                      "told apart from many accounts acting together, and accounts cannot be typed.")
ACCOUNTS_CAVEAT = ("Account types describe posting behaviour in this dataset only. Scheduling tools, "
                   "news feeds and people with daily routines look automated without being malicious, "
                   "and an account with one or two posts cannot be judged on its own.")
LEXICAL_CAVEAT = ("Text is compared by shared words and characters only, so copies that were "
                  "reworded (for example by an AI) are missed. Semantic mode catches light rewording.")
SEMANTIC_CAVEAT = ("Semantic mode catches light rewording only. Posts that push the same point in "
                   "entirely different words still look like ordinary same-topic discussion and are missed.")

PATTERN_PHRASE = {
    "burst": "posted close together in time",
    "regular": "posted at near-constant intervals",
    "hourly": "posted at the same minute of the hour",
    "daily": "posted at the same time of day",
}


def _verdict(swarm: float, beats: float | None, size: int) -> str:
    beats = 100.0 if beats is None else beats   # no dataset baseline: rely on the score alone
    if swarm >= STRONG_SCORE and beats >= STRONG_BEATS and size >= STRONG_SIZE:
        return "strong"
    if swarm >= MODERATE_SCORE and beats >= MODERATE_BEATS:
        return "moderate"
    return "low"


def _similar_word(similarity: float) -> str:
    return "identical" if similarity >= 99.5 else "near-identical" if similarity >= 85 else "similar"


def _reason(size: int, similarity: float, sync: dict) -> str:
    similarity = round(similarity, 1)
    sync = {**sync, "sync": round(sync["sync"], 1)}
    head = f"{size} posts with {_similar_word(similarity)} text (similarity {similarity:.0f})"
    pattern = sync["pattern"]
    if pattern is None:
        return (f"{head}, but their timing looks like any random group of {size} posts from this "
                f"dataset (synchrony 0).")
    detail = ""
    if pattern == "burst" and sync["median_gap_to_nearest"] is not None:
        detail = f" (typically {format_duration(sync['median_gap_to_nearest'])} from the nearest other post in the group)"
    elif pattern == "regular" and sync["mean_gap"]:
        detail = f" (about every {format_duration(sync['mean_gap'])})"
    text = f"{head}, {PATTERN_PHRASE[pattern]}{detail}; synchrony {sync['sync']:.0f}."
    if sync["beats_random"] is not None:
        text += (f" More synchronised than {sync['beats_random']:.1f}% of random groups of the same "
                 f"size from this dataset.")
    return text


def _sync_summary(sync: dict) -> dict:
    r1 = lambda d: {k: round(v, 1) for k, v in d.items()}
    return {
        "synchrony": round(sync["sync"], 1),
        "pattern": sync["pattern"],
        "beats_random": None if sync["beats_random"] is None else round(sync["beats_random"], 1),
        "sync_detail": {"measured": r1(sync["raw"]), "chance_level": r1(sync["baseline"]),
                        "score": r1(sync["adjusted"]), "compared_with": sync["baseline_source"]},
        "span_seconds": round(sync["span_seconds"], 1),
    }


def _post(ds: Dataset, p: int, **extra) -> dict:
    post = {"id": ds.ids[p], "content": ds.texts[p], "time": to_iso(ds.times[p]), **extra}
    if ds.accounts is not None:
        post["account"] = ds.accounts[p]
    return post


def _account_spread(ds: Dataset, members: np.ndarray) -> dict:
    """Who wrote a group's posts: how many accounts, and how concentrated."""
    if ds.accounts is None:
        return {}
    names = [ds.accounts[p] for p in members if ds.accounts[p]]
    if not names:
        return {"accounts": 0, "top_accounts": [], "accounts_note": "No account recorded for these posts."}
    unique, counts = np.unique(np.asarray(names, dtype=object), return_counts=True)
    top = np.argsort(-counts, kind="stable")[:5]
    n = len(unique)
    if n == 1:
        note = f"All {len(names)} posts come from one account, so this is one account repeating itself, not a group of accounts."
    elif counts.max() / len(names) >= 0.5:
        note = f"{n} accounts, but one of them wrote {counts.max()} of the {len(names)} posts."
    else:
        note = f"Written by {n} different accounts."
    return {"accounts": int(n), "accounts_note": note,
            "top_accounts": [{"id": str(unique[k]), "posts": int(counts[k])} for k in top]}


def _check_settings(threshold: float, min_size: int) -> None:
    if not 1 <= threshold <= 100:
        raise ValueError("Similarity threshold must be between 1 and 100.")
    if min_size < 2:
        raise ValueError("Minimum cluster size must be at least 2.")


def _crowding_warnings(scorer: SyncScorer, times: np.ndarray, half_life: float) -> list[str]:
    """A note when the timeline is so dense that any random handful of posts looks synchronised."""
    if len(times) < 10:
        return []
    chance = scorer.score(scorer.rng.choice(times, 5, replace=False))["baseline"]["burst"]
    if chance <= 90:
        return []
    return [f"Posts in this dataset are packed so closely in time that random groups already look "
            f"synchronised at a half-life of {format_duration(half_life)}. Use a shorter half-life "
            f"for more meaningful synchrony scores."]


def _cluster_record(ds: Dataset, scorer: SyncScorer, members: np.ndarray, similarity: float,
                    distinct_texts: int, sample: int) -> dict:
    times = ds.times[members]
    sync = scorer.score(times)
    swarm = math.sqrt(similarity * sync["sync"])
    by_time = members[np.argsort(times, kind="stable")]
    return {
        "verdict": _verdict(swarm, sync["beats_random"], len(members)),
        "swarm_score": round(swarm, 1),
        "similarity": round(similarity, 1),
        **_sync_summary(sync),
        "size": int(len(members)),
        "distinct_texts": distinct_texts,
        "first_time": to_iso(times.min()),
        "last_time": to_iso(times.max()),
        "reason": _reason(len(members), similarity, sync),
        **_account_spread(ds, members),
        "posts": [_post(ds, p) for p in by_time[:sample]],
        "post_ids": [ds.ids[p] for p in by_time],
        "times": [int(t) for t in ds.times[by_time][:MAX_CHART_TIMES]],
        "_members": members,
    }


def _clusters(ds: Dataset, index: SimilarityIndex, inverse: np.ndarray, found: list[dict],
              scorer: SyncScorer, sample: int) -> list[dict]:
    """Score each similar-text cluster's timing. Strongest first, numbered from 1."""
    order = np.argsort(inverse, kind="stable")
    bounds = np.searchsorted(inverse[order], np.arange(len(index.unique) + 1))
    clusters = []
    for c in found:
        members = np.sort(np.concatenate([order[bounds[u]:bounds[u + 1]] for u in c["members"]]))
        clusters.append(_cluster_record(ds, scorer, members, c["similarity"], int(len(c["members"])), sample))
    clusters.sort(key=lambda c: (-c["swarm_score"], -c["size"], -c["similarity"]))
    for k, c in enumerate(clusters, 1):
        c["id"] = k
    return clusters


def _membership(clusters: list[dict], n: int) -> tuple[np.ndarray, np.ndarray]:
    """(post -> id of its flagged group, or 0; post -> is it in any similar-text cluster)."""
    flagged_group = np.zeros(n, dtype=np.int64)
    in_similar = np.zeros(n, dtype=bool)
    for c in clusters:
        in_similar[c["_members"]] = True
        if c["verdict"] != "low":
            flagged_group[c["_members"]] = c["id"]
    return flagged_group, in_similar


def _seed_match(ds: Dataset, p: int, score: float, k: int, seed_time: float, half_life: float) -> dict:
    extra = {"similarity": round(score, 1), "seed": k + 1}
    if not np.isnan(seed_time):
        extra["sync_with_seed"] = round(pair_sync(ds.times[p], seed_time, half_life), 1)
    return _post(ds, p, **extra)


def _seed_verdict(n_hits: int, similarity: float, sync: dict, swarm: float, threshold: float) -> dict:
    if n_hits < 2:
        return {"verdict": "low",
                "reason": f"{n_hits} post(s) in the dataset score {threshold:g} or higher against the sample. "
                          f"Too few to judge timing."}
    return {"verdict": _verdict(swarm, sync["beats_random"], n_hits), "reason": _reason(n_hits, similarity, sync)}


def _seed_report(ds: Dataset, seeds: list[dict], index: SimilarityIndex, scorer: SyncScorer,
                 threshold: float, half_life: float, sample: int) -> tuple[dict | None, list[str]]:
    """Posts that match the sample posts, scored like a cluster. Returns (report, warnings)."""
    if not seeds:
        return None, []
    n = len(ds)
    inverse, seed_unique = index.inverse[:n], index.inverse[n:]
    scores = index.block(seed_unique)                       # seeds x unique texts
    scores[np.arange(len(seeds)), seed_unique] = 100.0
    best_seed = scores.argmax(axis=0)[inverse]              # per post: the sample it matches best
    post_score = scores.max(axis=0)[inverse]
    hits = np.flatnonzero(post_score >= threshold)
    hits = hits[np.argsort(-post_score[hits], kind="stable")]
    seed_times = parse_times([s.get("time") or "" for s in seeds])
    unreadable = sum(bool(s.get("time")) and bool(np.isnan(t)) for s, t in zip(seeds, seed_times))
    warnings = [f"Could not read the time of {unreadable} sample post(s); they were "
                f"used for text matching only."] if unreadable else []
    sync = scorer.score(np.concatenate([ds.times[hits], seed_times[~np.isnan(seed_times)]]))
    similarity = float(post_score[hits].mean()) if len(hits) else 0.0
    swarm = math.sqrt(similarity * sync["sync"])
    per_seed = np.bincount(best_seed[hits], minlength=len(seeds))
    verdict = _seed_verdict(len(hits), similarity, sync, swarm, threshold)
    report = {
        "seeds": [{"n": k + 1, "content": str(s["content"]), "time": to_iso(seed_times[k]),
                   "matches": int(per_seed[k])} for k, s in enumerate(seeds)],
        "n_matches": int(len(hits)),
        "verdict": verdict["verdict"],
        "swarm_score": round(swarm, 1),
        "similarity": round(similarity, 1),
        **_sync_summary(sync),
        "reason": verdict["reason"],
        "matches": [_seed_match(ds, p, float(post_score[p]), int(best_seed[p]), seed_times[best_seed[p]], half_life)
                    for p in hits[:max(sample, 200)]],
        "match_ids": [ds.ids[p] for p in hits],
    }
    return report, warnings


def _timeline(times: np.ndarray, in_flagged: np.ndarray, bins: int) -> dict:
    t0, t1 = float(times.min()), float(times.max())
    width = max((t1 - t0) / bins, 1.0)
    slot = np.minimum(((times - t0) // width).astype(np.int64), bins - 1)
    total = np.bincount(slot, minlength=bins)
    hot = np.bincount(slot[in_flagged], minlength=bins)
    return {"bin_seconds": width,
            "bins": [{"start": to_iso(t0 + k * width), "end": to_iso(t0 + (k + 1) * width),
                      "total": int(total[k]), "flagged": int(hot[k])} for k in range(bins)]}


def _activity(times: np.ndarray, in_flagged: np.ndarray) -> dict:
    """Posts by weekday (0 = Monday) and hour of day, UTC."""
    hour = ((times // 3600) % 24).astype(np.int64)
    weekday = ((times // 86400 + 3) % 7).astype(np.int64)      # 1970-01-01 was a Thursday
    cell = weekday * 24 + hour
    return {"total": np.bincount(cell, minlength=168).reshape(7, 24).tolist(),
            "flagged": np.bincount(cell[in_flagged], minlength=168).reshape(7, 24).tolist()}


def _evaluation(labels: list[str] | None, in_flagged: np.ndarray) -> dict | None:
    """Post-level accuracy against the answer key, with a breakdown per label."""
    if labels is None:
        return None
    names = np.array([str(l) for l in labels], dtype=object)
    by_label = {label: {"posts": int((names == label).sum()), "flagged": int(((names == label) & in_flagged).sum())}
                for label in sorted(set(names))}
    return {**confusion(in_flagged, np.array([is_positive_label(l) for l in labels])), "by_label": by_label}


def _account_report(ds: Dataset, index: SimilarityIndex, inverse: np.ndarray, flagged_group: np.ndarray,
                    scorer: SyncScorer, threshold: float, min_chars: int) -> dict | None:
    if ds.accounts is None:
        return None
    return profile_accounts(ds.accounts, ds.times, index, inverse, flagged_group, scorer,
                            threshold, min_chars, lambda p: _post(ds, p), ds.labels)


def analyse(ds: Dataset, seeds: list[dict] | None = None, threshold: float = DEFAULT_THRESHOLD,
            half_life: float = DEFAULT_HALF_LIFE, min_size: int = DEFAULT_MIN_SIZE, min_chars: int = DEFAULT_MIN_CHARS,
            semantic: bool = False, model: str = DEFAULT_MODEL, sample: int = 10,
            max_clusters: int = 200, timeline_bins: int = 60) -> dict:
    """Run the full detection. `seeds` is a list of {"content": str, "time": str | None}.
    Returns a JSON-serialisable report."""
    _check_settings(threshold, min_size)
    seeds = [s for s in (seeds or []) if str(s.get("content", "")).strip()]
    n = len(ds)

    index = SimilarityIndex(ds.texts + [str(s["content"]) for s in seeds], semantic=semantic, model=model)
    inverse = index.inverse[:n]
    ds_counts = np.bincount(inverse, minlength=len(index.unique))
    scan = index.scan(threshold, counts=ds_counts)
    scorer = SyncScorer(ds.times, half_life)
    # The scorer draws random groups as it goes, so the order of these steps is part of the result.
    warnings = ds.warnings + _crowding_warnings(scorer, ds.times, half_life)
    clusters = _clusters(ds, index, inverse, find_clusters(index, scan, threshold, min_size, min_chars, counts=ds_counts),
                         scorer, sample)
    flagged_group, in_similar = _membership(clusters, n)
    in_flagged = flagged_group > 0
    seed_report, seed_warnings = _seed_report(ds, seeds, index, scorer, threshold, half_life, sample)
    account_report = _account_report(ds, index, inverse, flagged_group, scorer, threshold, min_chars)

    for c in clusters:
        del c["_members"]
    verdicts = [c["verdict"] for c in clusters]
    n_flagged = len(clusters) - verdicts.count("low")
    return {
        "params": {"similarity_threshold": threshold, "half_life_seconds": half_life,
                   "min_cluster_size": min_size, "min_chars": min_chars, "semantic": bool(semantic),
                   "text_column": ds.text_col, "time_column": ds.time_col, "account_column": ds.account_col},
        "dataset": {"posts": n, "rows_read": ds.rows_read, "distinct_texts": int((ds_counts > 0).sum()),
                    "too_short_to_cluster": int((index.lengths[inverse] < min_chars).sum()),
                    "first_time": to_iso(ds.times.min()), "last_time": to_iso(ds.times.max())},
        "summary": {"flagged_clusters": n_flagged, "flagged_posts": int(in_flagged.sum()),
                    "strong_clusters": verdicts.count("strong"),
                    "moderate_clusters": verdicts.count("moderate"),
                    "similar_only_clusters": len(clusters) - n_flagged,
                    "similar_only_posts": int((in_similar & ~in_flagged).sum())},
        "clusters": clusters[:max_clusters],
        "clusters_omitted": max(0, len(clusters) - max_clusters),
        "seeds": seed_report,
        "accounts": account_report,
        "timeline": _timeline(ds.times, in_flagged, timeline_bins),
        "activity": _activity(ds.times, in_flagged),
        "evaluation": _evaluation(ds.labels, in_flagged),
        "caveats": CAVEATS + [NO_ACCOUNTS_CAVEAT if ds.accounts is None else ACCOUNTS_CAVEAT,
                              SEMANTIC_CAVEAT if semantic else LEXICAL_CAVEAT],
        "warnings": warnings + seed_warnings,
    }


# ---------------------------------------------------------------- CLI

def _pct(value: float | None) -> str:
    """Halves round up (81.25% -> 81.3%), the same as the dashboard shows."""
    return "n/a" if value is None else f"{int(value * 1000 + 0.5) / 10:.1f}%"


def _accuracy(e: dict) -> str:
    return (f"precision {_pct(e['precision'])}, recall {_pct(e['recall'])}, false-positive rate "
            f"{_pct(e['false_positive_rate'])} (TP {e['true_positives']}, FP {e['false_positives']}, "
            f"FN {e['false_negatives']}, TN {e['true_negatives']}).")


def _print_summary(report: dict) -> None:
    d, s = report["dataset"], report["summary"]
    for w in report["warnings"]:
        print(f"note: {w}")
    print(f"{d['posts']:,} posts ({d['distinct_texts']:,} distinct texts) from {d['first_time']} to {d['last_time']}.")
    print(f"Flagged: {s['flagged_clusters']} clusters ({s['strong_clusters']} strong, "
          f"{s['moderate_clusters']} moderate) covering {s['flagged_posts']:,} posts "
          f"({s['flagged_posts'] / d['posts']:.1%}).")
    print(f"Similar text but no unusual timing: {s['similar_only_clusters']} clusters, "
          f"{s['similar_only_posts']:,} posts (not flagged).")


def _print_seeds(seeds: dict | None, show: int) -> None:
    if not seeds:
        return
    print(f"\n=== Sample posts: {seeds['n_matches']} matches, verdict {seeds['verdict'].upper()}, "
          f"swarm score {seeds['swarm_score']:.0f} ===")
    print(f"  {seeds['reason']}")
    for m in seeds["matches"][:show]:
        print(f"    {m['similarity']:5.1f}  {m['time']}  [{m['id']}] {clip(m['content'], 80)}")


def _print_flagged(clusters: list[dict], show: int) -> None:
    shown = [c for c in clusters if c["verdict"] != "low"][:show]
    for c in shown:
        print(f"\n=== Cluster {c['id']}: {c['verdict'].upper()}, swarm score {c['swarm_score']:.0f} "
              f"(similarity {c['similarity']:.0f}, synchrony {c['synchrony']:.0f}) ===")
        print(f"  {c['reason']}")
        print(f"  {c['first_time']} to {c['last_time']}, {c['distinct_texts']} distinct texts")
        if c.get("accounts_note"):
            print(f"  {c['accounts_note']}")
        for p in c["posts"][:3]:
            print(f"    {p['time']}  [{p['id']}] {clip(p['content'], 80)}")
    if not shown:
        print("\nNo cluster is both similar and synchronised enough to flag.")


def _print_let_through(clusters: list[dict]) -> None:
    low = [c for c in clusters if c["verdict"] == "low"][:5]
    if low:
        print("\nLargest similar-text clusters that were NOT flagged (timing looks ordinary):")
    for c in low:
        print(f"  cluster {c['id']}: {c['size']} posts, similarity {c['similarity']:.0f}, "
              f"synchrony {c['synchrony']:.0f}  {clip(c['posts'][0]['content'], 60)}")


def _print_accounts(acc: dict | None, show: int) -> None:
    if not acc:
        print("\nNo account column was used, so accounts were not typed. Add --account-col if the data has one.")
        return
    print(f"\n=== Accounts: {acc['n_accounts']:,} in the data, {acc['flagged_accounts']:,} with a flagged type ===")
    for t in acc["types"]:
        print(f"  {t['label']:<24} {acc['type_counts'][t['key']]:>6}   {t['meaning']}")
    notable = [a for a in acc["accounts"] if a["type"] in FLAGGED_TYPES][:show]
    if notable:
        print("  Most notable accounts:")
    for a in notable:
        print(f"    {a['id']:<22} {TYPE_LABEL[a['type']]:<18} {a['posts']:>4} posts  {a['reasons'][0]}")
    if acc["evaluation"]:
        print(f"  Against the labels (an account counts as real when most of its posts are labelled as "
              f"swarm): {_accuracy(acc['evaluation'])}")


def _print_evaluation(ev: dict | None) -> None:
    if not ev:
        return
    print(f"\nAgainst the labels: {_accuracy(ev)}")
    for label, row in ev["by_label"].items():
        print(f"  {label:<24} {row['flagged']:>5} of {row['posts']:>5} flagged")


def print_report(report: dict, show: int = 10) -> None:
    _print_summary(report)
    _print_seeds(report["seeds"], show)
    _print_flagged(report["clusters"], show)
    _print_let_through(report["clusters"])
    _print_accounts(report["accounts"], show)
    _print_evaluation(report["evaluation"])
    print("\nRead this before drawing conclusions:")
    for c in report["caveats"]:
        print(f"  - {c}")


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Detect groups of posts that are similar in text and synchronised in time.")
    parser.add_argument("path", help="dataset file: CSV, TSV, JSON or JSON Lines")
    parser.add_argument("--text-col", help="content column (guessed if omitted)")
    parser.add_argument("--time-col", help="time column (guessed if omitted)")
    parser.add_argument("--account-col", default="auto",
                        help="account/author column, for account types (default: a column named account, "
                             "author, user_id or similar if present; pass 'none' to skip)")
    parser.add_argument("--label-col", help="ground-truth column; prints precision, recall and false-positive rate")
    parser.add_argument("--seed", action="append", default=[], metavar="TEXT",
                        help="a sample post to look for; repeat for several")
    parser.add_argument("--seeds-file", help="file of sample posts (same formats; needs a content column, time optional)")
    parser.add_argument("--threshold", type=float, default=DEFAULT_THRESHOLD, help="similarity needed to link two posts (default 60)")
    parser.add_argument("--half-life", default="10m", help="time gap at which two posts score 50 for synchrony (default 10m)")
    parser.add_argument("--min-size", type=int, default=DEFAULT_MIN_SIZE, help="smallest cluster to report (default 5)")
    parser.add_argument("--min-chars", type=int, default=DEFAULT_MIN_CHARS, help="ignore shorter posts when clustering (default 20)")
    parser.add_argument("--semantic", action="store_true", help="also use sentence embeddings (catches rewording)")
    parser.add_argument("--model", default=DEFAULT_MODEL)
    parser.add_argument("--max-rows", type=int)
    parser.add_argument("--show", type=int, default=10, help="clusters to print (default 10)")
    parser.add_argument("--json", action="store_true", help="print the full report as JSON")
    parser.add_argument("--out", help="write the full report as JSON to this file")
    return parser


def _seeds(texts: list[str], seeds_file: str | None) -> list[dict]:
    seeds = [{"content": text} for text in texts]
    if seeds_file:
        sf = load_dataset(seeds_file, require_time=False)
        seeds += [{"content": c, "time": to_iso(t)} for c, t in zip(sf.texts, sf.times)]
    return seeds


def main(argv: list[str] | None = None) -> int:
    args = _parser().parse_args(argv)
    ds = load_dataset(args.path, args.text_col, args.time_col, label_col=args.label_col, max_rows=args.max_rows,
                      account_col=None if args.account_col.lower() == "none" else args.account_col)
    report = analyse(ds, _seeds(args.seed, args.seeds_file), args.threshold, parse_duration(args.half_life),
                     args.min_size, args.min_chars, args.semantic, args.model)
    text = json.dumps(report, ensure_ascii=False, indent=2)
    if args.out:
        with open(args.out, "w", encoding="utf-8") as fh:
            fh.write(text)
    if args.json:
        print(text)
        return 0
    print_report(report, args.show)
    if args.out:
        print(f"\nFull report written to {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(run_cli(main))